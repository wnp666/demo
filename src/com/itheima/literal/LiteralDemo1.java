package com.itheima.literal;

public class LiteralDemo1 {
    //    输出恐龙的信息：霸王龙，8岁，11.5吨，公
    public static void main(String[] args) {
//    输出恐龙的名字
        System.out.println("霸王龙");
//    输出恐龙的年龄
        System.out.println("8岁");
//    输出恐龙的重量
        System.out.println("11.5吨");
//    输出恐龙的性别
        System.out.println("公");
    }
};
